/**
 * Inlines `assets/vendor/*.js` and `assets/page/*.js` into a generated TypeScript module.
 *
 * Reading them from disk at runtime breaks as soon as untube is bundled into a consumer's build:
 * the sandbox files are resolved relative to `import.meta.url`, which then points at the app's
 * entry file, not at this package. Embedding the source text instead makes the sandbox independent
 * of how (and where) the bundle is deployed.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "src", "pot", "sandbox", "assets.generated.ts");

function readAssetDir(dir) {
  const abs = path.join(root, dir);
  const names = fs
    .readdirSync(abs, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));

  if (names.length === 0) {
    throw new Error(`untube: no sandbox assets found in ${dir}`);
  }

  return names
    .map((name) => {
      const source = fs.readFileSync(path.join(abs, name), "utf8");
      return `  ${JSON.stringify(name)}: ${JSON.stringify(source)},`;
    })
    .join("\n");
}

const vendor = readAssetDir("assets/vendor");
const page = readAssetDir("assets/page");

const contents = `// AUTO-GENERATED by scripts/generate-assets.js - do not edit by hand.
// Sandbox scripts are inlined so they survive bundling and container images that ship only the
// bundle. See src/pot/sandbox/paths.ts for why.

export const VENDOR_ASSETS: Readonly<Record<string, string>> = {
${vendor}
};

export const PAGE_ASSETS: Readonly<Record<string, string>> = {
${page}
};
`;

fs.writeFileSync(outFile, contents);
// stderr, so machine-readable npm output (e.g. `npm pack --json`) stays parseable.
console.error(
  `untube: wrote ${path.relative(root, outFile)} (${(Buffer.byteLength(contents) / 1024).toFixed(1)} KiB)`,
);
